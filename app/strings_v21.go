// detailLabel 把运行记录里 app 自己写入的来源说明（菜单栏、工作台）换成当前语言；其他说明原样显示。
func detailLabel(d string) string {
	switch d {
	case "menu bar":
		return tr("src_menubar")
	case wbDetail:
		return tr("workbench")
	}
	return d
}
